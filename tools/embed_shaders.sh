#!/bin/sh
set -eu

out=$1; shift
guard=$(basename "$out" | tr 'a-z.-' 'A-Z__')

{
    printf '/* Generated by %s -- do not edit. Edit the files in src/shaders instead. */\n' "$0"
    printf '#ifndef __%s\n#define __%s\n' "$guard" "$guard"
    for f in "$@"; do
        name=$(basename "$f")
        stem=${name%.*}
        case "${name##*.}" in
            vert) stage=vertex ;;
            frag) stage=fragment ;;
            geom) stage=geometry ;;
            comp) stage=compute ;;
            *) stage=${name##*.} ;;
        esac
        printf '\nstatic const char *const %s_%s_shader_source =\n' "$stem" "$stage"
        sed -e 's/\r$//' -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/"/' -e 's/$/\\n"/' "$f"
        printf ';\n'
    done
    printf '\n#endif // __%s \n' "$guard"
} > "$out"
